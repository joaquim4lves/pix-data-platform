"""Render the portable model SQL as Athena views.

Raw external tables are Terraform's. This script creates the other Glue
databases if they are missing and replaces the views. The catalog prefix
must match ``catalog_prefix`` in ``infra/terraform/envs/dev`` (default ``pix``).
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

SQL_DIR = Path(__file__).resolve().parent / "sql"
DEFAULT_OUTPUT = Path(__file__).resolve().parent / "athena" / "views.sql"
LAYERS = ("seeds", "staging", "intermediate", "marts", "checks")
DATABASES = ("raw",) + LAYERS
SCHEMA_REF = re.compile(r"\b(raw|seeds|staging|intermediate|marts|checks)\.")
PREFIX_RE = re.compile(r"^[a-z][a-z0-9_]{0,30}$")


def qualify(sql: str, prefix: str) -> str:
    return SCHEMA_REF.sub(lambda match: f"{prefix}_{match.group(1)}.", sql)


def render(prefix: str = "pix") -> str:
    if not PREFIX_RE.fullmatch(prefix):
        raise ValueError(f"catalog prefix must match {PREFIX_RE.pattern}, got {prefix!r}")
    parts = [
        "-- Athena views for the DuckDB models in transform/sql.",
        "-- Generated by: python -m transform.athena_sql",
        f"-- Catalog prefix: {prefix}",
        "-- Matches the Glue databases from infra/terraform (catalog_prefix).",
        "-- Raw tables are external tables owned by Terraform.",
        "-- Run this script in the pix workgroup after apply. Do not edit by hand.",
        "",
    ]
    for name in DATABASES:
        parts.append(f"CREATE DATABASE IF NOT EXISTS {prefix}_{name};")
    parts.append("")
    for layer in LAYERS:
        directory = SQL_DIR / layer
        for path in sorted(directory.glob("*.sql")):
            body = qualify(path.read_text(encoding="utf-8").strip().rstrip(";"), prefix)
            parts.append(f"CREATE OR REPLACE VIEW {prefix}_{layer}.{path.stem} AS")
            parts.append(body + ";")
            parts.append("")
    return "\n".join(parts).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--prefix", default="pix")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit 1 when the output file does not match the renderer.",
    )
    args = parser.parse_args(argv)
    rendered = render(args.prefix)
    if args.check:
        current = args.output.read_text(encoding="utf-8") if args.output.exists() else ""
        if current != rendered:
            print(f"{args.output} is stale; run python -m transform.athena_sql", file=sys.stderr)
            return 1
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(rendered, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
